"""Generate the loading PRX at the fixed address reserved by KokakuNative."""
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parent.parent
raw = root / 'diagnostics/loading-generated'
subprocess.run([str(root / 'tools/PSPRecomp/build/psp_recomp.exe'),
                str(root / 'extracted/PSP_GAME/USRDIR/loading.psp.prx'),
                '--auto', str(raw), '0x08B20000', '16384'], check=True)
destination = root / 'tools/PSPRecomp/profiles/kokaku/generated'
for source in sorted(raw.glob('*.cpp')) + [raw / 'generated_units.hpp']:
    text = source.read_text()
    text = text.replace('generated_units.hpp', 'loading_units.hpp')
    text = text.replace('recomp_unit_', 'recomp_loading_unit_')
    text = text.replace('register_generated_unit_', 'register_loading_unit_')
    text = text.replace('register_generated_functions', 'register_loading_functions')
    # Each ELF has a separate import table; binding-cache slots are runtime-wide.
    text = re.sub(r'invoke_import_cached\((\d+)u',
                  lambda match: 'invoke_import_cached(' + str(2000 + int(match[1])) + 'u', text)
    output = destination / source.name.replace('generated_', 'loading_')
    text = '// Generated by tools/generate_kokaku_loading.py.\n' + text
    if not output.exists() or output.read_text() != text:
        output.write_text(text, newline='\n')
