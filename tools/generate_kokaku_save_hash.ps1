$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent
Set-Location -LiteralPath $projectRoot
$profile = 'tools/PSPRecomp/profiles/kokaku'
$rawOutput = Join-Path $projectRoot 'diagnostics/save-hash-generated.cpp'
& tools/PSPRecomp/build/psp_recomp.exe extracted/PSP_GAME/USRDIR/main.psp.prx "$profile/config/save_hash_blocks.csv" $rawOutput
if ($LASTEXITCODE -ne 0) { throw 'Save hash code generation failed' }
$source = [IO.File]::ReadAllText($rawOutput)
# The manual generator also emits every PSP import. The existing main registry
# owns those imports; retain only the missing code and its address registrations.
$source = [regex]::Replace($source, '(?s)static void import_0.*?(?=void register_generated_functions)', '')
$source = [regex]::Replace($source, '(?m)^.*runtime\.register_function\(.*&import_.*\r?\n', '')
$source = $source.Replace('register_generated_functions', 'register_kokaku_save_hash')
$outputPath = Join-Path $projectRoot "$profile/generated/kokaku_save_hash.cpp"
[IO.File]::WriteAllText($outputPath, "// Generated by tools/generate_kokaku_save_hash.ps1; do not edit manually.`n" + $source)
